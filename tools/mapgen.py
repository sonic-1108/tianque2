"""Turn the owner's two Gemini images into map data.
  height image: a shaded-relief picture (light baked in), so it is used for its broad shape and for where the
  ground is rugged, not read literally; the fine ridges come from noise in world.ts.
  colour image: painted top-down map in the same layout: the ground colours (public/terrain_color.jpg) and the
  water mask (its blue).
python3 tools/mapgen.py height.jpeg color.jpeg"""
import sys, base64
import numpy as np
from PIL import Image, ImageFilter

hp, cp = sys.argv[1], sys.argv[2]
H = Image.open(hp).convert('L').resize((1024, 1024), Image.LANCZOS)
C = Image.open(cp).convert('RGB')
h = np.asarray(H, dtype=np.float32) / 255

def blur(a, r):
    im = Image.fromarray(np.clip(a * 255, 0, 255).astype(np.uint8))
    return np.asarray(im.filter(ImageFilter.GaussianBlur(r)), dtype=np.float32) / 255

big = blur(h, 30)                      # the broad shape
rough = blur(np.abs(h - blur(h, 4)) * 4, 12)  # how rugged
c = np.asarray(C.resize((1024, 1024), Image.LANCZOS), dtype=np.float32) / 255
r, g, b = c[..., 0], c[..., 1], c[..., 2]
snow = blur(((r + g + b) / 3 > 0.72).astype(np.float32) * ((np.maximum(r, np.maximum(g, b)) - np.minimum(r, np.minimum(g, b))) < 0.12), 6)
cw = np.asarray(C.resize((512, 512), Image.LANCZOS), dtype=np.float32) / 255
wr, wg, wb = cw[..., 0], cw[..., 1], cw[..., 2]
water = ((wb > 0.45) & (wb - wr > 0.25) & (wb - wg > 0.08)).astype(np.uint8)
# drop specks (bluish shadows in the snow): keep pixels with enough water neighbours
from PIL import ImageFilter as F
wm = Image.fromarray(water * 255).filter(F.MinFilter(3)).filter(F.MaxFilter(5))
water = (np.asarray(wm) > 127).astype(np.uint8)
print('water fraction', water.mean())

def b64u8(a, n):
    im = Image.fromarray(np.clip(a * 255, 0, 255).astype(np.uint8)).resize((n, n), Image.LANCZOS)
    return base64.b64encode(np.asarray(im, dtype=np.uint8).tobytes()).decode()

bits = np.packbits(water.flatten())
out = f"""// Generated by tools/mapgen.py from the owner's Gemini maps. Do not edit by hand.
// 128 x 128 (broad shape, ruggedness, snow) and 512 x 512 (water) samples over the whole map, north at the top.
export const MAP_N = 128;
export const WATER_N = 512;
export const BIG = '{b64u8(big, 128)}';
export const ROUGH = '{b64u8(np.clip(rough, 0, 1), 128)}';
export const SNOW = '{b64u8(snow, 128)}';
export const WATER = '{base64.b64encode(bits.tobytes()).decode()}';
"""
open('src/game/mapdata.ts', 'w').write(out)
C.save('public/terrain_color.jpg', quality=86)
Image.fromarray(water * 255).save('/tmp/claude-0/-home-claude/f117edb1-8259-5424-8679-94b61e80e348/scratchpad/water.png')
Image.fromarray((np.clip(rough,0,1)*255).astype(np.uint8)).save('/tmp/claude-0/-home-claude/f117edb1-8259-5424-8679-94b61e80e348/scratchpad/rough.png')
Image.fromarray((big*255).astype(np.uint8)).save('/tmp/claude-0/-home-claude/f117edb1-8259-5424-8679-94b61e80e348/scratchpad/big.png')
print('ok', len(out) // 1024, 'KB')
